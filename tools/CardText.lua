-- =========================================================================
-- CARD RULES TEXT TRANSLATIONS (not part of the addon; run outside the game)
--   lua5.1 tools/CardText.lua [addonDir]
-- The translations live in tools/cardtext/*.lua, one entry per distinct English
-- rules text: { en = "...", de = "...", fr = "...", es = "...", zh = "...", it = "..." }.
-- Many cards share a text, so each is translated once. Inside a translation:
--   «self»          the card's own name in that language
--   «zone:<Zone>»   that zone's name in that language (from the generated game names)
-- Writes ../ForeverCCG_Languages/<code>_CardText.lua with card.<ID>.text for every
-- card, and lists texts that have no translation yet (they stay English).
-- Run it again after adding cards, or after tools/FetchGameNames.sh.
-- =========================================================================
local dir = arg[1] or "."
local packDir = dir .. "/../ForeverCCG_Languages"
local PARTS = { "keywords", "anthems", "spells", "specials" }
local LANGS = { de = "deDE", fr = "frFR", es = "esES", zh = "zhCN", it = "itIT" }

TTS = {}
function TTS:AddCards(t) for id, c in pairs(t) do TTS.Cards[id] = c end end
CreateFrame = function() return setmetatable({}, { __index = function() return function() end end }) end
for line in io.lines(dir .. "/ForeverCCG.toc") do
    line = line:gsub("\r", "")
    if line:match("^Cards\\") then assert(loadfile(dir .. "/" .. line:gsub("\\", "/")))() end
end

-- English text -> { de = ..., ... }
local dict, dupes = {}, {}
for _, part in ipairs(PARTS) do
    for _, e in ipairs(dofile(dir .. "/tools/cardtext/" .. part .. ".lua")) do
        if dict[e.en] then dupes[#dupes + 1] = e.en end
        dict[e.en] = e
    end
end

-- Everything the pack already says in one language (names of cards and zones), except card text
local function PackStrings(code)
    local strings = {}
    TTS.Locale = { wanted = code, Register = function(_, c, t) for k, v in pairs(t) do strings[k] = v end end }
    for line in io.lines(packDir .. "/ForeverCCG_Languages.toc") do
        line = line:gsub("\r", "")
        if line:match("%.lua$") and not line:match("_CardText%.lua$") then
            local chunk = loadfile(packDir .. "/" .. line)
            if chunk then chunk() end
        end
    end
    return strings
end

local function Quote(s) return '"' .. s:gsub("\\", "\\\\"):gsub('"', '\\"'):gsub("\n", "\\n") .. '"' end

local ids = {}
for id, c in pairs(TTS.Cards) do if c.text and c.text ~= "" then ids[#ids + 1] = id end end
table.sort(ids)

local untranslated = {}
for lang, code in pairs(LANGS) do
    local strings = PackStrings(code)
    local out = {
        "--[[",
        "    ForeverCCG - Tragic: The Saddening Engine  |  © 2026 the_naked_gypsy",
        "    Copyright (c) 2026 the_naked_gypsy. All Rights Reserved.",
        "",
        "    This file is part of ForeverCCG. See LICENSE.txt for terms.",
        "    World of Warcraft names, creatures, icons and models are the property of",
        "    Blizzard Entertainment, Inc. and are not claimed by this notice.",
        "]]",
        "-- =========================================================================",
        "-- CARD RULES TEXT (generated by tools\\CardText.lua from tools\\cardtext\\*.lua;",
        "-- do not edit here, change the translation there and run the tool again)",
        "-- =========================================================================",
        'local CODE = "' .. code .. '"',
        "if TTS.Locale.wanted ~= CODE then return end",
        "",
        "TTS.Locale:Register(CODE, {",
    }
    local n = 0
    for _, id in ipairs(ids) do
        local card = TTS.Cards[id]
        local e = dict[card.text]
        local t = e and e[lang]
        if t then
            local selfName = strings["card." .. id .. ".name"] or card.name
            t = t:gsub("«self»", function() return selfName end)
            t = t:gsub("«zone:([^»]+)»", function(z) return strings["zone." .. z] or z end)
            out[#out + 1] = "    [" .. Quote("card." .. id .. ".text") .. "] = " .. Quote(t) .. ","
            n = n + 1
        else
            untranslated[card.text] = true
        end
    end
    out[#out + 1] = "})"
    out[#out + 1] = ""
    local f = assert(io.open(packDir .. "/" .. code .. "_CardText.lua", "wb"))
    f:write(table.concat(out, "\n")); f:close()
    print(string.format("%s: %d of %d card texts", code, n, #ids))
end

local list = {}
for t in pairs(untranslated) do list[#list + 1] = t end
table.sort(list)
for _, t in ipairs(list) do print("NOT TRANSLATED  " .. t) end
for _, t in ipairs(dupes) do print("DUPLICATE ENTRY  " .. t) end
